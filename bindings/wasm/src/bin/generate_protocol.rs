#[derive(Clone, Debug, Eq, Ord, PartialEq, PartialOrd)]
enum Schema {
    Null,
    Boolean,
    SafeInteger,
    Number,
    String,
    LiteralString(String),
    Array(Box<Self>),
    Object(BTreeMap<String, Property>),
    Union(Vec<Self>),
}

#[derive(Clone, Debug, Eq, Ord, PartialEq, PartialOrd)]
struct Property {
    schema: Schema,
    optional: bool,
}

#[derive(Clone, Debug)]
struct Definition {
    name: &'static str,
    schema: Schema,
}

#[derive(Default)]
struct Registry {
    definitions: Vec<Definition>,
}

impl Registry {
    fn add<T: Serialize>(&mut self, name: &'static str, samples: &[T]) {
        assert!(
            !samples.is_empty(),
            "{name} requires a representative value"
        );
        assert!(
            self.definitions
                .iter()
                .all(|definition| definition.name != name),
            "duplicate schema name {name}"
        );
        let values = samples
            .iter()
            .map(|sample| {
                serde_json::to_value(sample)
                    .unwrap_or_else(|error| panic!("cannot serialize {name}: {error}"))
            })
            .collect::<Vec<_>>();
        let enum_like = values.iter().all(|value| match value {
            serde_json::Value::String(_) => true,
            serde_json::Value::Object(fields) if fields.len() == 1 => fields
                .keys()
                .next()
                .is_some_and(|key| key.as_bytes().first().is_some_and(u8::is_ascii_uppercase)),
            _ => false,
        });
        let schema = values
            .iter()
            .map(|value| infer(value, enum_like, None))
            .reduce(merge)
            .expect("samples are non-empty");
        assert_no_empty_arrays(&schema);
        self.definitions.push(Definition { name, schema });
    }

    fn declaration(&self) -> String {
        let mut output = String::from(
            "// @generated by generate_protocol; do not edit.\n\
             /** A JSON number admitted only when Number.isSafeInteger(value) is true. */\n\
             export type SafeInteger = number;\n",
        );
        for definition in &self.definitions {
            output.push_str("export type ");
            output.push_str(definition.name);
            output.push_str(" = ");
            output.push_str(&render_root(
                &definition.schema,
                definition.name,
                &self.definitions,
            ));
            output.push_str(";\n");
        }
        output
    }
}

fn infer(value: &serde_json::Value, literal_strings: bool, field: Option<&str>) -> Schema {
    match value {
        serde_json::Value::Null => Schema::Null,
        serde_json::Value::Bool(_) => Schema::Boolean,
        serde_json::Value::Number(number) if number.is_i64() || number.is_u64() => {
            Schema::SafeInteger
        }
        serde_json::Value::Number(_) => Schema::Number,
        serde_json::Value::String(value)
            if literal_strings || matches!(field, Some("kind" | "protocol" | "region")) =>
        {
            Schema::LiteralString(value.clone())
        }
        serde_json::Value::String(_) => Schema::String,
        serde_json::Value::Array(values) => {
            let element = values
                .iter()
                .map(|value| infer(value, false, None))
                .reduce(merge)
                .unwrap_or_else(|| panic!("every Vec sample must contain a representative item"));
            Schema::Array(Box::new(element))
        }
        serde_json::Value::Object(fields) => {
            let error_payload = fields
                .get("kind")
                .and_then(serde_json::Value::as_str)
                .is_some_and(|kind| kind == "error");
            Schema::Object(
                fields
                    .iter()
                    .map(|(name, value)| {
                        (
                            name.clone(),
                            Property {
                                schema: infer(value, error_payload && name == "value", Some(name)),
                                optional: false,
                            },
                        )
                    })
                    .collect(),
            )
        }
    }
}

fn merge(left: Schema, right: Schema) -> Schema {
    if left == right {
        return left;
    }
    match (left, right) {
        (Schema::Array(left), Schema::Array(right)) => {
            Schema::Array(Box::new(merge(*left, *right)))
        }
        (Schema::Object(left), Schema::Object(right))
            if objects_are_same_product(&left, &right) =>
        {
            Schema::Object(merge_objects(left, right))
        }
        (Schema::Union(left), Schema::Union(right)) => union(left.into_iter().chain(right)),
        (Schema::Union(left), right) => union(left.into_iter().chain([right])),
        (left, Schema::Union(right)) => union([left].into_iter().chain(right)),
        (left, right) => union([left, right]),
    }
}

fn objects_are_same_product(
    left: &BTreeMap<String, Property>,
    right: &BTreeMap<String, Property>,
) -> bool {
    let discriminators_differ = match (left.get("kind"), right.get("kind")) {
        (Some(left), Some(right)) => left.schema != right.schema,
        _ => false,
    };
    let external_variants_differ = left.len() == 1
        && right.len() == 1
        && left.keys().next() != right.keys().next()
        && left
            .keys()
            .chain(right.keys())
            .all(|key| key.as_bytes().first().is_some_and(u8::is_ascii_uppercase));
    !discriminators_differ && !external_variants_differ
}

fn merge_objects(
    mut left: BTreeMap<String, Property>,
    mut right: BTreeMap<String, Property>,
) -> BTreeMap<String, Property> {
    let names = left
        .keys()
        .chain(right.keys())
        .cloned()
        .collect::<BTreeSet<_>>();
    names
        .into_iter()
        .map(|name| {
            let property = match (left.remove(&name), right.remove(&name)) {
                (Some(left), Some(right)) => Property {
                    schema: merge(left.schema, right.schema),
                    optional: left.optional || right.optional,
                },
                (Some(mut property), None) | (None, Some(mut property)) => {
                    property.optional = true;
                    property
                }
                (None, None) => unreachable!("field came from one object"),
            };
            (name, property)
        })
        .collect()
}

fn union(items: impl IntoIterator<Item = Schema>) -> Schema {
    let mut flattened = Vec::new();
    for item in items {
        match item {
            Schema::Union(items) => flattened.extend(items),
            item => flattened.push(item),
        }
    }
    let mut normalized: Vec<Schema> = Vec::new();
    for item in flattened {
        if let Some(index) = normalized
            .iter()
            .position(|existing| union_variants_are_compatible(existing, &item))
        {
            let existing = normalized.remove(index);
            normalized.push(merge(existing, item));
        } else if !normalized.contains(&item) {
            normalized.push(item);
        }
    }
    normalized.sort();
    Schema::Union(normalized)
}

fn union_variants_are_compatible(left: &Schema, right: &Schema) -> bool {
    let (Schema::Object(left), Schema::Object(right)) = (left, right) else {
        return false;
    };
    match (left.get("kind"), right.get("kind")) {
        (Some(left), Some(right)) => left.schema == right.schema,
        _ if left.len() == 1 && right.len() == 1 => left.keys().next() == right.keys().next(),
        _ => false,
    }
}

fn assert_no_empty_arrays(schema: &Schema) {
    match schema {
        Schema::Array(element) => assert_no_empty_arrays(element),
        Schema::Object(fields) => {
            for property in fields.values() {
                assert_no_empty_arrays(&property.schema);
            }
        }
        Schema::Union(items) => {
            for item in items {
                assert_no_empty_arrays(item);
            }
        }
        Schema::Null
        | Schema::Boolean
        | Schema::SafeInteger
        | Schema::Number
        | Schema::String
        | Schema::LiteralString(_) => {}
    }
}

fn render_root(schema: &Schema, current: &str, definitions: &[Definition]) -> String {
    render_schema(schema, current, definitions, None, false)
}

fn render(
    schema: &Schema,
    current: &str,
    definitions: &[Definition],
    field: Option<&str>,
) -> String {
    render_schema(schema, current, definitions, field, true)
}

fn render_schema(
    schema: &Schema,
    current: &str,
    definitions: &[Definition],
    field: Option<&str>,
    allow_reference: bool,
) -> String {
    if allow_reference {
        if let Some(reference) = reference_for(schema, current, definitions, field) {
            return reference.to_owned();
        }
    }
    match schema {
        Schema::Null => "null".to_owned(),
        Schema::Boolean => "boolean".to_owned(),
        Schema::SafeInteger => "SafeInteger".to_owned(),
        Schema::Number => "number".to_owned(),
        Schema::String => "string".to_owned(),
        Schema::LiteralString(value) => serde_json::to_string(value).expect("string serialization"),
        Schema::Array(element) => {
            let rendered = render(element, current, definitions, field);
            if rendered.contains(" | ") {
                format!("({rendered})[]")
            } else {
                format!("{rendered}[]")
            }
        }
        Schema::Object(fields) => {
            let fields = fields
                .iter()
                .map(|(name, property)| {
                    let optional = if property.optional { "?" } else { "" };
                    format!(
                        "{}{optional}: {}",
                        render_key(name),
                        render(&property.schema, current, definitions, Some(name))
                    )
                })
                .collect::<Vec<_>>()
                .join("; ");
            format!("{{ {fields} }}")
        }
        Schema::Union(items) => {
            let mut rendered = Vec::new();
            for item in items {
                let item = render(item, current, definitions, field);
                if !rendered.contains(&item) {
                    rendered.push(item);
                }
            }
            rendered.join(" | ")
        }
    }
}

fn reference_for<'a>(
    schema: &Schema,
    current: &str,
    definitions: &'a [Definition],
    field: Option<&str>,
) -> Option<&'a str> {
    let matches = definitions
        .iter()
        .take_while(|definition| definition.name != current)
        .filter(|definition| definition.name != current && definition.schema == *schema)
        .collect::<Vec<_>>();
    if matches.len() == 1 {
        return Some(matches[0].name);
    }
    if matches.len() > 1 {
        if field.is_some_and(|field| field.contains("span") || field == "primary") {
            if let Some(definition) = matches
                .iter()
                .find(|definition| definition.name == "ByteSpan")
            {
                return Some(definition.name);
            }
        }
        if matches!(field, Some("columns" | "rows")) {
            if let Some(definition) = matches
                .iter()
                .find(|definition| definition.name == "AxisRange")
            {
                return Some(definition.name);
            }
        }
        return Some(matches[0].name);
    }
    if matches!(current, "Value" | "ScalarValue")
        && field == Some("value")
        && matches!(schema, Schema::LiteralString(_))
    {
        if let Some(definition) = definitions.iter().find(|definition| {
            definition.name == "CellError" && schema_is_represented_by(&definition.schema, schema)
        }) {
            return Some(definition.name);
        }
    }
    if let Some(preferred) = preferred_reference(current, field) {
        if let Some(definition) = definitions
            .iter()
            .find(|definition| definition.name == preferred)
        {
            if schema_is_represented_by(&definition.schema, schema) {
                return Some(definition.name);
            }
        }
    }
    None
}

