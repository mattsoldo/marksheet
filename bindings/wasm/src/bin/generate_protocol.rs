/// Returns true when `observed` is a sample-derived subset of `complete`.
/// This is used only with an explicit semantic field-to-alias preference; it
/// never guesses a named type merely because two unrelated objects overlap.
fn schema_is_represented_by(complete: &Schema, observed: &Schema) -> bool {
    if complete == observed {
        return true;
    }
    match (complete, observed) {
        (Schema::Union(complete), Schema::String)
            if complete
                .iter()
                .all(|item| matches!(item, Schema::LiteralString(_))) =>
        {
            true
        }
        (Schema::Union(complete), Schema::Union(observed)) => observed.iter().all(|observed| {
            complete
                .iter()
                .any(|complete| schema_is_represented_by(complete, observed))
        }),
        (Schema::Union(complete), observed) => complete
            .iter()
            .any(|complete| schema_is_represented_by(complete, observed)),
        (Schema::Array(complete), Schema::Array(observed)) => {
            schema_is_represented_by(complete, observed)
        }
        (Schema::Object(complete), Schema::Object(observed)) => {
            observed.iter().all(|(name, observed)| {
                complete.get(name).is_some_and(|complete| {
                    schema_is_represented_by(&complete.schema, &observed.schema)
                })
            })
        }
        _ => false,
    }
}

fn render_key(name: &str) -> String {
    if name.bytes().enumerate().all(|(index, byte)| {
        byte.is_ascii_alphanumeric() || byte == b'_' || (index > 0 && byte == b'$')
    }) {
        name.to_owned()
    } else {
        serde_json::to_string(name).expect("object key serialization")
    }
}

fn identifier<T: std::str::FromStr>(value: &str) -> T
where
    T::Err: std::fmt::Debug,
{
    value.parse().expect("valid protocol sample identifier")
}

