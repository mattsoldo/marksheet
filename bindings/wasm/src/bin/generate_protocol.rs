//! Generates the public TypeScript worker protocol from serialized Rust values.
//!
//! The generator deliberately constructs the real protocol types rather than
//! maintaining a second, hand-written model. Struct literals name every field,
//! and each enum sample set is checked by an exhaustive match. Consequently a
//! Rust field or variant change either fails this binary to compile or changes
//! the inferred declaration checked into `protocol.d.ts`.

#![forbid(unsafe_code)]

